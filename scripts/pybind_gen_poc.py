import argparse
import os
import sys

# Use local scripts module for loading
import loader

def to_cpp_class_name(name):
    """Converts snake_case name to PascalCase for C++ class."""
    if not name:
        return ""
    parts = name.split('_')
    return "".join(p.capitalize() for p in parts)

def load_adapted_model(yaml_path):
    """Loads model using native loader and adapts to list of dicts."""
    # loader._load_one_model returns an orderedmultidict
    # NOTE:
    # _load_one_model is currently a private helper used by the native
    # generation pipeline (scripts/generate.py).
    # It is reused here intentionally for this PoC to ensure identical
    # model parsing semantics. This can be wrapped or promoted to a
    # public API once the design is finalized.
    model = loader._load_one_model(yaml_path)
    
    # Flatten to list of dicts to match previous 'parse_yaml' output format
    # which 'generate_binding' expects.
    adapted = []
    
    # top-level definition
    # loader returns: {'type': 'obj_def', 'name': 'design', ...}
    top_item = {}
    if model['type'] == 'obj_def':
        top_item['obj_def'] = model['name']
    elif model['type'] == 'class_def':
        top_item['obj_def'] = model['name'] # reuse obj_def key for class extraction
    
    if model.get('extends'):
        top_item['extends'] = model['extends']
        
    adapted.append(top_item)
    
    # Properties
    # model.allitems() iterates over multi-dict entries
    for key, value in model.allitems():
        if key == 'property':
            # value is an orderedmultidict or dict-like
            prop_item = {'property': value['name']}
            if 'type' in value:
                prop_item['type'] = value['type']
            if 'vpi' in value:
                prop_item['vpi'] = value['vpi']
            if 'card' in value:
                prop_item['card'] = value['card']
            adapted.append(prop_item)
            
    return adapted

def generate_header(out_file):
    out_file.write("// AUTOGENERATED POC - DO NOT EDIT\n")
    out_file.write("#include <pybind11/pybind11.h>\n")
    out_file.write("#include <memory>\n") # For std::unique_ptr
    out_file.write("namespace py = pybind11;\n\n")

def generate_binding(data, yaml_path, out_file):
    # Find obj_def and extends
    obj_def = None
    extends = None
    
    for item in data:
        if 'obj_def' in item:
            obj_def = item['obj_def']
        if 'extends' in item:
            extends = item['extends']
            
    if not obj_def:
        print(f"Error: Could not determine class name from {yaml_path}")
        sys.exit(1)

    class_name = to_cpp_class_name(obj_def)
    
    # Best effort header include
    filename = os.path.basename(yaml_path)
    header_name = os.path.splitext(filename)[0] + ".h"
    out_file.write(f"#include <uhdm/{header_name}>\n\n")

    out_file.write(f"void bind_{class_name}(py::module_& m) {{\n")
    
    cpp_class = f"uhdm::{class_name}"
    
    if extends:
        cpp_base = f"uhdm::{to_cpp_class_name(extends)}"
        out_file.write(f"  py::class_<{cpp_class}, {cpp_base}, std::unique_ptr<{cpp_class}, py::nodelete>> cls(m, \"{class_name}\");\n")
    else:
        out_file.write(f"  py::class_<{cpp_class}, std::unique_ptr<{cpp_class}, py::nodelete>> cls(m, \"{class_name}\");\n")
    
    # Generate getters
    for item in data:
        if 'property' in item:
            prop_name = item['property']
            prop_type = item.get('type')
            
            # Filter for scalar types
            if prop_type in ['string', 'int', 'bool', 'unsigned int']:
                getter_name = "get" + to_cpp_class_name(prop_name)
                # Use pythonic read-only property: obj.prop_name
                out_file.write(f"  cls.def_property_readonly(\"{prop_name}\", &{cpp_class}::{getter_name});\n")

    out_file.write("}\n")

def generate_from_parsed_model(parsed_items, yaml_path, out_path):
    with open(out_path, 'w') as f:
        generate_header(f)
        generate_binding(parsed_items, yaml_path, f)

def main():
    """
    Usage:
      python3 scripts/pybind_gen_poc.py --yaml model/design.yaml --out output_design.cpp
    """
    parser = argparse.ArgumentParser(description="Generate Pybind11 bindings from UHDM YAML.")
    parser.add_argument("--yaml", required=True, help="Path to one model/*.yaml file")
    parser.add_argument("--out", required=True, help="Output .cpp file path")
    args = parser.parse_args()

    data = load_adapted_model(args.yaml)
    generate_from_parsed_model(data, args.yaml, args.out)

if __name__ == "__main__":
    main()
