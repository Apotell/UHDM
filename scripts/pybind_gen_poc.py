import argparse
import os
import sys

# Use local scripts module for loading
import loader
import config

def generate_header(out_file):
    out_file.write("// AUTOGENERATED POC - DO NOT EDIT\n")
    out_file.write("#include <pybind11/pybind11.h>\n")
    out_file.write("#include <pybind11/stl.h>\n") # For std::vector
    out_file.write("#include <memory>\n") # For std::unique_ptr
    out_file.write("namespace py = pybind11;\n\n")

def generate_binding(model_name, model_def, out_file):
    class_name = config.make_class_name(model_name)
    
    # Best effort header include: use the snake_case model name directly
    # Example: model "design" -> #include <uhdm/design.h>
    header_name = f"{model_name}.h"
    out_file.write(f"#include <uhdm/{header_name}>\n")

    # Include headers for referenced types to avoid incomplete type errors in vectors
    includes = set()
    iter_items = model_def.allitems() if hasattr(model_def, 'allitems') else model_def.items()
    for key, value in iter_items:
        if key in ['class_ref', 'obj_ref']:
             type_name = value.get('type')
             if type_name and type_name != 'any':
                 includes.add(f"#include <uhdm/{type_name}.h>")
    
    for inc in sorted(includes):
        out_file.write(f"{inc}\n")

    out_file.write("\n")
    out_file.write(f"void bind_{class_name}(py::module_& m) {{\n")
    
    cpp_class = f"uhdm::{class_name}"
    
    extends = model_def.get('extends')
    if extends:
        cpp_base = f"uhdm::{config.make_class_name(extends)}"
        out_file.write(f"  py::class_<{cpp_class}, {cpp_base}, std::unique_ptr<{cpp_class}, py::nodelete>> cls(m, \"{class_name}\");\n")
    else:
        out_file.write(f"  py::class_<{cpp_class}, std::unique_ptr<{cpp_class}, py::nodelete>> cls(m, \"{class_name}\");\n")
    
    # Generate getters
    # Handle robust iteration
    iter_items = model_def.allitems() if hasattr(model_def, 'allitems') else model_def.items()

    for key, value in iter_items:
        if key == 'property':
            # value is dict-like: {'name': ..., 'type': ..., 'card': ..., ...}
            prop_name = value.get('name')
            prop_type = value.get('type')
            card = value.get('card')
            
            # Filter for scalar types
            if prop_type in ['string', 'int', 'bool', 'unsigned int']:
                # The PoC required "get" + PascalCase
                suffix = config.make_func_name(prop_name, card)
                func_name = f"get{suffix}"
                
                # Python attribute name: snake_case (prop_name is typically snake_case)
                python_name = prop_name
                
                out_file.write(f"  cls.def_property_readonly(\"{python_name}\", &{cpp_class}::{func_name});\n")

        elif key in ['class_ref', 'obj_ref']:
            prop_name = value.get('name')
            prop_type = value.get('type')
            card = value.get('card')

            # Determine Accessor
            suffix = config.make_func_name(prop_name, card)
            func_name = f"get{suffix}" # e.g. getTopModules
            python_name = prop_name
            
            if card == '1':
                # Return Policy
                # For pointers, reference is usually safe as we don't transfer ownership
                policy = "py::return_value_policy::reference"
                # Use lambda to resolve overload ambiguity (const vs non-const)
                out_file.write(f"  cls.def_property_readonly(\"{python_name}\", []({cpp_class}* self) {{ return self->{func_name}(); }}, {policy});\n")
            
            elif card == 'any':
                # For vectors, we need a lambda to handle nullptr -> empty list
                # And we return by value (copying the vector of pointers), 
                # relying on pybind11 to convert std::vector<T*> to [T*] with reference policy for elements.
                
                # Element type class name
                elem_type = config.make_class_name(value.get('type'))
                elem_cpp_type = f"uhdm::{elem_type}"
                
                out_file.write(f"  cls.def_property_readonly(\"{python_name}\", []({cpp_class}* self) {{\n")
                out_file.write(f"    std::vector<{elem_cpp_type}*> res;\n")
                out_file.write(f"    if (auto* vec = self->{func_name}()) {{\n")
                out_file.write(f"      res.reserve(vec->size());\n")
                out_file.write(f"      res.insert(res.end(), vec->begin(), vec->end());\n")
                out_file.write(f"    }}\n")
                out_file.write(f"    return res;\n")
                out_file.write(f"  }}, py::return_value_policy::reference);\n")

    out_file.write("}\n")

def main():
    parser = argparse.ArgumentParser(description="Generate Pybind11 bindings for all UHDM models.")
    parser.add_argument("--out_dir", default="python/pybind11/bindings/autogen", help="Output directory for generated bindings")
    args = parser.parse_args()

    print("Loading models...")
    models = loader.load_models()
    
    if not os.path.exists(args.out_dir):
        os.makedirs(args.out_dir)
        
    print(f"Generating bindings for {len(models)} models into {args.out_dir}...")
    
    for model_name, model_def in models.items():
        # Valid type filter: only obj_def and class_def
        def_type = model_def.get('type')
        if def_type not in ['obj_def', 'class_def']:
            continue
            
        class_name = config.make_class_name(model_name)
        out_filename = f"bind_{class_name}.cpp"
        out_path = os.path.join(args.out_dir, out_filename)
        
        with open(out_path, 'w') as f:
            generate_header(f)
            generate_binding(model_name, model_def, f)
            
    print("Done.")

if __name__ == "__main__":
    main()
